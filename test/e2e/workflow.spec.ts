import { expect, test } from "@playwright/test";
import path from "node:path";

const shot = (name: string) => path.resolve("docs", "screenshots", name);

test("trace, explore, rehearse, improve, compare, save, and export", async ({ page }) => {
  const consoleErrors: string[] = [];
  let progressReads = 0;
  page.on("console", (message) => { if (message.type() === "error") consoleErrors.push(message.text()); });
  page.on("response", (response) => { if (response.url().endsWith("/api/scenario/evidence")) progressReads += 1; });
  await page.goto("/");
  await expect(page.getByLabel("Local chain status")).toBeVisible();
  await page.getByRole("button", { name: "Continue to review question" }).click();
  await page.getByRole("button", { name: "Start guided review" }).click();
  await page.getByRole("button", { name: "Build scenario" }).click();
  await page.getByRole("dialog", { name: "Build local scenario" }).getByRole("button", { name: "Load guided example" }).click();
  await page.getByTestId("deploy-scenario").click();
  await expect(page.getByTestId("scenario-builder")).toBeHidden();
  await expect(page.getByTestId("discovery")).toContainText("STEP 1 OF 4");
  await expect(page.getByTestId("analysis-metrics")).toHaveCount(0);
  await expect(page.getByTestId("control-graph").locator(".safe-node")).toHaveCount(0);
  await page.getByTestId("trace-next").click();
  await expect(page.getByTestId("control-graph").locator(".safe-node")).toHaveCount(3);
  await page.getByTestId("trace-next").click();
  await expect(page.getByTestId("control-graph").locator(".signer-node")).toHaveCount(6);
  await page.getByTestId("trace-next").click();
  await expect(page.getByTestId("analysis-metrics")).toContainText("100,000 DUSD");
  await page.getByRole("combobox", { name: "Key budget" }).selectOption("1");
  await expect(page.getByTestId("analysis-metrics")).toContainText("MAXIMUM WITH UP TO 1 KEY");
  await expect(page.locator(".authority-copy")).toContainText("No group of up to 1 key can authorize a pause");
  await page.getByRole("combobox", { name: "Key budget" }).selectOption("2");
  await page.getByRole("combobox", { name: "Key budget" }).selectOption("6");
  await expect(page.getByTestId("analysis-metrics")).toContainText("100,000 DUSD");
  await page.getByRole("combobox", { name: "Key budget" }).selectOption("2");
  await page.screenshot({ path: shot("01-overview-1440.png"), animations: "disabled" });
  await page.getByRole("checkbox", { name: "Include Harbor" }).uncheck();
  await expect(page.getByTestId("analysis-metrics")).toContainText("65,000 DUSD");
  await page.getByRole("checkbox", { name: "Include Harbor" }).check();
  for (const name of ["Atlas", "Harbor", "Grove"]) await page.getByRole("checkbox", { name: `Include ${name}` }).uncheck();
  await expect(page.getByTestId("rehearse")).toBeDisabled();
  for (const name of ["Atlas", "Harbor", "Grove"]) await page.getByRole("checkbox", { name: `Include ${name}` }).check();
  await page.getByRole("button", { name: /^B\s+0x/ }).click();
  await expect(page.getByTestId("analysis-metrics")).toContainText("0 DUSD");
  await page.getByRole("button", { name: /^B\s+0x/ }).click();
  await page.getByTestId("rehearse").click();
  await expect(page.getByTestId("reset-after-base")).toBeVisible();
  await expect(page.locator(".position-card").filter({ hasText: "PAUSED" })).toHaveCount(3);
  await page.screenshot({ path: shot("02-base-paused.png"), animations: "disabled" });
  await page.getByTestId("reset-after-base").click();
  await page.getByRole("button", { name: "Design a Safe change" }).click();
  await expect(page.getByTestId("apply-patch")).toBeDisabled();
  await page.getByRole("button", { name: "Load guided Harbor example" }).click();
  await expect(page.getByTestId("proposal")).toContainText("100,000 → 65,000 DUSD");
  await expect(page.getByTestId("proposal-meaning")).toContainText("reduces the largest amount");
  await page.getByRole("button", { name: "Save this proposal locally" }).click();
  await expect(page.getByTestId("proposal")).toContainText("Open a saved proposal");
  await page.screenshot({ path: shot("03-change-preview.png"), animations: "disabled" });
  await page.getByTestId("apply-patch").click();
  await expect(page.getByTestId("replay")).toBeVisible();
  await expect(page.getByTestId("comparison")).toContainText("100,000 → 65,000 DUSD");
  await page.getByTestId("replay").click();
  await expect(page.getByText("After withdrawal check: 34,999 DUSD")).toBeVisible();
  await expect(page.getByTestId("outcome-panel")).toContainText("withdrawal succeeded");
  await expect(page.getByTestId("outcome-panel")).toContainText("Expected: pause rejected");
  await expect(page.getByTestId("result-verdict")).toContainText("Pause results matched the prediction for all 3 selected vaults");
  await expect(page.getByTestId("outcome-panel")).toContainText("Not attempted in this rehearsal");
  await expect(page.getByTestId("outcome-panel")).toContainText("withdrawal succeeded");
  await page.getByRole("tab", { name: "Explore" }).click();
  await page.getByRole("button", { name: /^B\s+0x/ }).click();
  await page.getByRole("tab", { name: "Results" }).click();
  await expect(page.getByTestId("outcome-panel")).toContainText("Keys: A + B");
  await expect(page.getByTestId("record-notice")).toContainText("different exploratory selection");
  await page.getByRole("button", { name: "Show receipts and save review" }).click();
  await expect(page.getByTestId("evidence").locator(".event-row")).toHaveCount(10);
  await page.screenshot({ path: shot("04-replayed-1440.png"), animations: "disabled" });
  await page.getByRole("button", { name: "Table" }).click();
  await expect(page.getByTestId("control-table")).toContainText("Insufficient approvals");
  await page.getByRole("textbox", { name: "Review name" }).fill("Harbor separation review");
  await page.getByRole("textbox", { name: "Review note" }).fill("A+B no longer reaches Harbor.");
  await page.getByRole("button", { name: "Save review locally" }).click();
  await page.getByRole("button", { name: /Harbor separation review/ }).click();
  await expect(page.getByRole("dialog", { name: "Saved reviews" })).toContainText("A+B no longer reaches Harbor.");
  await page.getByRole("dialog", { name: "Saved reviews" }).getByRole("button", { name: "Close" }).click();
  const exported = await page.evaluate(async () => (await fetch("/api/scenario/export")).json());
  expect(exported.sha256).toHaveLength(64);
  expect(exported.markdown).toContain("not a certification of safety");
  expect(exported.json).not.toContain("privateKey");
  const downloads: string[] = [];
  page.on("download", (download) => downloads.push(download.suggestedFilename()));
  await page.getByRole("button", { name: "Export evidence" }).click();
  await expect.poll(() => downloads.length).toBe(2);
  expect(downloads.some((name) => name.endsWith("-decision-brief.md"))).toBe(true);
  expect(progressReads).toBeGreaterThan(0);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: shot("05-replayed-mobile.png"), animations: "disabled" });
  expect(consoleErrors).toEqual([]);
});

test("build a different on-chain arrangement", async ({ page }) => {
  await page.goto("/");
  await expect(page.getByLabel("Local chain status")).toBeVisible();
  await page.getByRole("button", { name: "Skip introduction" }).click();
  await page.getByRole("button", { name: "Build scenario" }).click();
  const builder = page.getByTestId("scenario-builder");
  const cards = builder.locator(".builder-card");
  await cards.nth(0).getByLabel("Vault name").fill("Reserve");
  await cards.nth(0).getByLabel("DemoUSD units").fill("10000");
  await cards.nth(0).getByRole("checkbox", { name: "B" }).uncheck();
  await cards.nth(0).getByRole("checkbox", { name: "F" }).check();
  await cards.nth(1).getByLabel("Vault name").fill("Bridge");
  await cards.nth(1).getByLabel("DemoUSD units").fill("20000");
  await cards.nth(2).getByLabel("Vault name").fill("Grants");
  await cards.nth(2).getByLabel("DemoUSD units").fill("30000");
  await cards.nth(2).getByLabel("Approvals required").selectOption("3");
  await builder.getByTestId("deploy-scenario").click();
  await expect(builder).toBeHidden();
  await expect(page.locator(".position-card").first()).toContainText("Reserve");
  await expect(page.locator(".position-card")).toContainText(["10,000 DUSD", "20,000 DUSD", "30,000 DUSD"]);
  await page.getByRole("button", { name: "Table" }).click();
  await page.getByRole("button", { name: "Show complete map" }).click();
  await expect(page.getByTestId("control-table")).toContainText("3 required");
  await expect(page.getByTestId("control-table")).toContainText("A, C, F");
  await page.getByRole("button", { name: "Build scenario" }).click();
  await page.getByRole("dialog", { name: "Build local scenario" }).getByRole("button", { name: "Load guided example" }).click();
  await page.getByTestId("deploy-scenario").click();
  await expect(page.getByTestId("scenario-builder")).toBeHidden();
  await expect(page.locator(".position-card").first()).toContainText("Atlas");
});
