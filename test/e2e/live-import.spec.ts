import { expect, test } from '@playwright/test';

test('read-only import validates inputs, maps real local Safes, and preserves the rehearsal', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByLabel('Local chain status')).toBeVisible();
  await page.getByRole('button', { name: 'Skip introduction' }).click();
  const before = await (await page.request.get('/api/scenario/snapshot')).json();
  await page.getByRole('button', { name: 'Import Live Safes', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Import Live Safes' });
  await expect(dialog.getByRole('button', { name: 'Load Sepolia examples' })).toBeVisible();
  await dialog.getByLabel('Safe address 1', { exact: true }).fill('not-an-address');
  await expect(dialog.getByText('Enter a valid EVM address', { exact: false })).toBeVisible();
  await expect(dialog.getByRole('button', { name: 'Fetch & Map Architecture' })).toBeDisabled();
  await dialog.getByRole('button', { name: 'Load local demo Safes' }).click();
  await dialog.getByLabel('Safe address 1', { exact: true }).fill('0x0000000000000000000000000000000000000001');
  await dialog.getByRole('button', { name: 'Fetch & Map Architecture' }).click();
  await expect(dialog.getByRole('alert')).toContainText('Not a recognized Safe');
  await dialog.getByRole('button', { name: 'Load local demo Safes' }).click();
  await dialog.getByRole('button', { name: 'Fetch & Map Architecture' }).click();
  await expect(page.getByTestId('live-safe-view')).toBeVisible();
  await expect(page.locator('.live-graph .safe-node')).toHaveCount(3);
  await expect(page.locator('.live-graph .signer-node')).toHaveCount(5);
  await expect(page.locator('.live-banner')).toContainText('read-only mode');
  await expect(page.getByRole('button', { name: /^Rehearse/ })).toHaveCount(0);
  await page.getByRole('button', { name: 'Show group for all' }).click();
  await expect(page.locator('.canvas-callout')).toContainText('meets 3 of 3 owner thresholds');
  await page.getByRole('button', { name: 'Table', exact: true }).click();
  await expect(page.locator('.control-table')).toContainText(before.positions[0].controller.address.toLowerCase());
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export read-only snapshot' }).click();
  expect((await downloaded).suggestedFilename()).toContain('breakpoint-readonly-31337');
  await page.getByRole('button', { name: 'Graph', exact: true }).click();
  await page.setViewportSize({ width: 1366, height: 768 });
  await page.screenshot({ path: 'docs/screenshots/08-live-safe-import.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.getByRole('button', { name: 'Return to local rehearsal' }).click();
  await expect(page.getByLabel('Local chain status')).toBeVisible();
  const after = await (await page.request.get('/api/scenario/snapshot')).json();
  expect(after.runId).toBe(before.runId);
  expect(after.blockHash).toBe(before.blockHash);
  expect(after.positions).toEqual(before.positions);
});
